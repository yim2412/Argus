-- 알림이 실제로 사용자 화면에 닿았는가.
--
-- **`notified` 와 같은 칸을 쓰지 않는다.** `notified` 는 예산·심각도 판정("보낼
-- 대상인가")이고 발송과는 일부러 분리돼 있다 — 알림을 끈 상태로도 "켜면 몇 건이
-- 올 것인가"를 재기 위해서다(fusion.py 의 `notify_enabled` 주석). 그 분리는 옳다.
--
-- 문제는 **분리해 놓고 전달 쪽을 아무 데도 안 적었다는 것**이다. 전달 실패는
-- 로그 한 줄로만 남아서, DB 로는 "이 알림이 닿았나"에 영영 답할 수 없었다.
--
-- 2026-09-09 에 드러났다: 09-06 20:24·20:47 두 건이 `Shell_NotifyIcon` 오류
-- (-2147467259)로 전달되지 않았는데 두 사건 다 `notified=1` 이라, DB 만 보면
-- 발송 67건이 전부 성공으로 보였다. 그 두 건이 **마지막 알림 시도**였고, 실패가
-- 3일 동안 아무 화면에도 드러나지 않았다. 규칙 4("조용히 실패하지 않는다") 위반이다.
--
-- 값의 뜻:
--   delivered = NULL  발송을 시도하지 않았다 (판정에서 걸렸거나 알림 스위치가 꺼짐)
--   delivered = 1     전달자가 성공을 돌려줬다
--   delivered = 0     시도했고 실패했다 — 이유는 delivery_error 에 있다
--
-- 시도조차 안 한 것과 시도해서 실패한 것을 가르는 것이 요점이다. 둘을 0 으로 합치면
-- "알림을 꺼 둔 조용함"과 "깨져서 조용함"이 같은 값이 되고, 그게 정확히 이번에
-- 3일을 놓친 이유다.

ALTER TABLE incidents ADD COLUMN delivered      INTEGER;  -- NULL(미시도) | 1(전달) | 0(실패)
ALTER TABLE incidents ADD COLUMN delivery_error TEXT;     -- 사람이 읽는 실패 사유 한 줄
