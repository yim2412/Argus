-- RSS 순간값이 왜 튀는지 지금 데이터로는 못 정한다.
--
-- 2026-08-04 에 예산(300MB)을 넘긴 시점의 실측 RSS 는 447 / 469 / 553 / 588MB 였는데,
-- 같은 구간 `self_telemetry` 평균은 65MB 이고 `private_mb` 는 501MB 로 평탄하다.
-- **순간값만 튄다.** 즉 어떤 컴포넌트의 tick 안에서 잠깐 크게 잡았다 놓는 것이고,
-- 5초마다 찍는 표본은 그 봉우리를 대부분 놓친다.
--
-- 봉우리를 더 자주 찍는 것은 답이 아니다 — 관측이 예산을 먹는다(설계 규칙 1).
-- 대신 **표본을 찍은 그 순간 어떤 컴포넌트가 tick 중이었는지**를 같이 남긴다.
-- 스로틀이 켜진 표본만 모아 이 값의 분포를 보면 범인이 드러난다.
-- 롤업 실행과 겹치는 건이 있어 롤업 쿼리가 의심되지만, 아직 측정하지 않았다.
--
-- 비용은 tick 당 dict 쓰기 두 번이다. tick 마다 RSS 를 재는 방식(델타 측정)은
-- psutil 호출이 초당 수십 번 늘어 관측자가 무거워진다 — 같은 이유로 뺐다.

ALTER TABLE self_telemetry ADD COLUMN active TEXT;  -- 표본 시점에 tick 중이던 컴포넌트 (쉼표 구분, 오래 돈 순)
