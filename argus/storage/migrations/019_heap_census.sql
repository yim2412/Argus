-- 프로세스 수명 내내 자라는 메모리의 정체를 묻는다 (2026-08-25).
--
-- **무엇이 관측됐나.** 두 기계 모두 `private_mb` 가 프로세스 수명 내내 단조 증가한다.
-- 노트북은 부팅 후 117시간에 40 -> 198MB, 이 PC 는 세션마다 52 -> 250MB.
-- 재시작하면 매번 52MB 로 돌아가므로 **세션 간 누적은 없다** — 프로세스 수명 내
-- 성장이다. 5일 연속 켜 두는 기계에서는 그 구분이 실질적으로 무의미하다.
--
-- **개수만 세면 절반을 놓친다.** CPython 은 원자값만 든 컨테이너를 untrack 하고
-- `str`·`bytes`·`int` 는 애초에 `gc` 가 추적하지 않는다. 실측(2026-08-25 스모크):
-- 문자열만 든 `dict` 5만 개를 만들어도 **객체 수는 +2**, 원소 수는 +50,014 였다.
-- 캐시가 대개 그 모양이므로, `container_items` 가 없으면 이 계측은 정작 자라는 것을
-- 통째로 놓친다.
--
-- 다만 `container_items` 가 세는 것은 untracked 객체 자신이 아니라 **그것을 담은
-- tracked 컨테이너의 크기**다(그 객체들은 `gc.get_objects()` 에 나오지도 않는다).
-- 간접 신호이므로 방향은 잡히지만, 최상위 컨테이너 자신이 untracked 면 못 본다.
--
-- **어디가 아닌지는 이미 안다.** 같은 구간에서 `threads`(36.9) 와 `handles`(472) 가
-- 소수점까지 상수였다. 스레드 누수도 핸들 누수도 아니고 **파이썬 힙 안에서** 자란다.
-- 그래서 OS 지표가 아니라 `gc` 가 보는 객체를 센다.
--
-- **왜 한 행에 JSON 인가.** 타입마다 한 행씩 넣으면 5분 주기에 상위 20종만 해도
-- 하루 5,760행이고, 정작 묻는 것은 "무엇이 언제부터 늘었나"라 타입별로 나눠 담을
-- 이유가 없다. 한 행이면 하루 288행이고 조회는 JSON 하나만 풀면 된다.
--
-- **`scan_ms` 를 같이 남기는 이유.** 관측자는 가벼워야 한다(설계 규칙 1). 이 계측이
-- 자기 비용을 기록하지 않으면 나중에 "Argus 가 무거워진 게 이것 때문인가"에 답할 수
-- 없다. 임포트 직후 32,112 객체에서 3.95ms 였고, 객체 수에 비례해 늘어난다.
--
-- `tracemalloc` 은 넣지 않았다. 상시 켜면 할당마다 후킹이 걸려 설계 규칙 1 과
-- 정면으로 충돌한다. 타입별 개수로 정체가 안 잡히면 그때 진단 모드로 도입한다.

CREATE TABLE IF NOT EXISTS heap_census (
    ts            REAL    NOT NULL,
    total_objects   INTEGER NOT NULL,  -- gc 가 추적하는 전체 객체 수
    container_items INTEGER NOT NULL,  -- 모든 컨테이너의 len() 합 (비추적 객체를 여기서 잡는다)
    scan_ms         REAL    NOT NULL,  -- 이 측정 자체가 쓴 시간
    top_types       TEXT    NOT NULL   -- JSON {"dict": {"n": 1303, "items": 16989}, ...}
                                       -- 상위 선정은 **원소 수 기준**이다. 개수 상위는
                                       -- 늘 function/tuple 로 고정돼 아무것도 말하지 않는다
);

CREATE INDEX IF NOT EXISTS idx_heap_census_ts ON heap_census(ts);
