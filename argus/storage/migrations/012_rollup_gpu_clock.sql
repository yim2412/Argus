-- GPU SM 클럭을 1분 롤업에 남긴다.
--
-- **왜 지금 넣는가: 원본(`gpu_metrics`)은 24시간만 남는다.** 등급의 "현재 손실" 축은
-- "같은 부하에서 평소보다 클럭이 얼마나 깎였나"를 보는데, 그러려면 며칠치 비교가
-- 필요하다. 접지 않으면 매일 사라지므로 **오늘 넣지 않으면 오늘치는 영구히 없다**
-- (Phase 6-B 가 남긴 교훈: "지금 없는 과거는 되살릴 수 없다").
--
-- 손실 축이 실제로 채택될지는 아직 모른다. 그래도 컬럼부터 넣는 이유는 비용이
-- 비대칭이기 때문이다 — 안 쓰면 REAL 두 칸이 낭비되지만, 나중에 필요해지면
-- 그때까지의 과거가 통째로 없다.
--
-- 두 통계량을 두는 이유: `mean` 은 그 분의 대표 클럭(기준선을 세우는 쪽),
-- `min` 은 가장 깎였을 때(스로틀이 실제로 얼마나 물었는지). 최대는 넣지 않는다 —
-- 부스트 상한은 하드웨어 상수라 매분 기록해도 새 정보가 없다.
ALTER TABLE metrics_1m ADD COLUMN gpu_clock_sm_mean REAL;
ALTER TABLE metrics_1m ADD COLUMN gpu_clock_sm_min  REAL;
